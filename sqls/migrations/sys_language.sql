-- 语言配置表
CREATE TABLE IF NOT EXISTS sys_language (
    ID BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    SYS_COMPANY_ID BIGINT UNSIGNED NOT NULL DEFAULT 0,
    CODE VARCHAR(50) NOT NULL COMMENT '语言代码 zh-CN, en-US 等',
    NAME VARCHAR(255) NOT NULL COMMENT '语言名称',
    IS_DEFAULT VARCHAR(1) NOT NULL DEFAULT 'N' COMMENT '是否默认语言 Y/N',
    IS_ACTIVE VARCHAR(1) NOT NULL DEFAULT 'Y' COMMENT '是否激活 Y/N',
    CREATE_BY VARCHAR(80) NOT NULL DEFAULT '',
    CREATE_TIME DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATE_BY VARCHAR(80) NOT NULL DEFAULT '',
    UPDATE_TIME DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    INDEX idx_company (SYS_COMPANY_ID),
    INDEX idx_code (CODE),
    INDEX idx_active (IS_ACTIVE),
    UNIQUE KEY uk_company_code (SYS_COMPANY_ID, CODE)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='语言配置表';

