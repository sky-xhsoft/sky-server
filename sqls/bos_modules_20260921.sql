-- ---------- N1 用户环境变量(用户 × 模块 × 键) ----------
CREATE TABLE IF NOT EXISTS sys_user_pref (
  ID            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  SYS_COMPANY_ID INT UNSIGNED NOT NULL DEFAULT 0,
  SYS_USER_ID   INT UNSIGNED NOT NULL DEFAULT 0 COMMENT '用户(0=全局/系统级)',
  MODULE        VARCHAR(64)  NOT NULL DEFAULT '' COMMENT '命名空间,如 option/template.xxx/layout',
  NAME          VARCHAR(128) NOT NULL DEFAULT '' COMMENT '键',
  VALUE         TEXT NULL COMMENT '值',
  DESCRIPTION   VARCHAR(255) NULL COMMENT '说明',
  CREATE_BY     VARCHAR(80) NULL,
  CREATE_TIME   DATETIME NULL,
  UPDATE_BY     VARCHAR(80) NULL,
  UPDATE_TIME   DATETIME NULL,
  IS_ACTIVE     CHAR(1) NOT NULL DEFAULT 'Y',
  UNIQUE KEY uk_user_module_name (SYS_USER_ID, MODULE, NAME),
  KEY idx_user_pref_user (SYS_USER_ID),
  PRIMARY KEY (ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户环境变量';

-- ---------- N3 自动任务定义 ----------
CREATE TABLE IF NOT EXISTS sys_schedule (
  ID            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  SYS_COMPANY_ID INT UNSIGNED NOT NULL DEFAULT 0,
  NAME          VARCHAR(255) NOT NULL COMMENT '任务名称',
  DISPLAY_NAME  VARCHAR(255) NULL,
  ACTION_TYPE   VARCHAR(32)  NULL DEFAULT 'go' COMMENT 'url/sp/js/py/go/bsh',
  ACTION_CONTENT TEXT NULL COMMENT '动作内容(url / 脚本 / 扩展名)',
  CRON          VARCHAR(64)  NULL COMMENT '触发表达式(5段:分 时 日 月 周)',
  IS_ACTIVE     CHAR(1) NOT NULL DEFAULT 'Y',
  LAST_RUN_AT   DATETIME NULL,
  NEXT_RUN_AT   DATETIME NULL,
  DESCRIPTION   VARCHAR(2000) NULL,
  CREATE_BY     VARCHAR(80) NULL,
  CREATE_TIME   DATETIME NULL,
  UPDATE_BY     VARCHAR(80) NULL,
  UPDATE_TIME   DATETIME NULL,
  PRIMARY KEY (ID),
  KEY idx_schedule_next (IS_ACTIVE, NEXT_RUN_AT)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='自动任务定义';

-- ---------- N3 自动任务执行日志 ----------
CREATE TABLE IF NOT EXISTS sys_schedule_log (
  ID            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  SYS_COMPANY_ID INT UNSIGNED NOT NULL DEFAULT 0,
  SCHEDULE_ID   INT UNSIGNED NOT NULL COMMENT '任务ID',
  RUN_AT        DATETIME NULL COMMENT '执行时间',
  STATUS        VARCHAR(16) NULL COMMENT 'SUCCESS/FAIL',
  MESSAGE       VARCHAR(2000) NULL,
  RESULT        TEXT NULL,
  ERROR         TEXT NULL,
  DURATION_MS   INT NULL,
  CREATE_BY     VARCHAR(80) NULL,
  CREATE_TIME   DATETIME NULL,
  UPDATE_BY     VARCHAR(80) NULL,
  UPDATE_TIME   DATETIME NULL,
  IS_ACTIVE     CHAR(1) NOT NULL DEFAULT 'Y',
  PRIMARY KEY (ID),
  KEY idx_schedule_log_task (SCHEDULE_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='自动任务执行日志';

-- ---------- N2 动作执行日志 ----------
CREATE TABLE IF NOT EXISTS sys_action_log (
  ID            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  SYS_COMPANY_ID INT UNSIGNED NOT NULL DEFAULT 0,
  ACTION_ID     INT UNSIGNED NULL COMMENT '动作ID',
  ACTION_NAME   VARCHAR(80) NULL,
  TABLE_NAME    VARCHAR(255) NULL,
  RECORD_ID     INT UNSIGNED NULL,
  PARAMS        TEXT NULL,
  RESULT        TEXT NULL,
  ERROR         TEXT NULL,
  EXEC_TIME     DATETIME NULL,
  DURATION_MS   INT NULL,
  EXEC_BY       VARCHAR(80) NULL,
  CREATE_TIME   DATETIME NULL,
  UPDATE_TIME   DATETIME NULL,
  IS_ACTIVE     CHAR(1) NOT NULL DEFAULT 'Y',
  PRIMARY KEY (ID),
  KEY idx_action_log_action (ACTION_ID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='动作执行日志';

-- ---------- C4 虚拟字段:sys_column 加列 ----------
ALTER TABLE sys_column
  ADD COLUMN IF NOT EXISTS IS_VIRTUAL CHAR(1) NULL DEFAULT 'N' COMMENT 'Y:虚拟字段,只读展示不落库' AFTER PROPS,
  ADD COLUMN IF NOT EXISTS EXPRESSION VARCHAR(2000) NULL COMMENT '虚拟字段计算表达式' AFTER IS_VIRTUAL;